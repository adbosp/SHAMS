"""Web game build and smoke test (Three.js + Vite), run from the SHAMS web toolchain folder.

* ``build_web``: puts the project files (code, models, textures) in a work folder inside the toolchain, adds
  ``index.html`` + ``src/main.ts`` when the project has none (main calls the scene module's ``start(container)``),
  and runs ``vite build``. Node resolves ``three`` and ``vite`` from the toolchain, so nothing is installed into
  the user's project.
* ``WebBuildWorker`` (capability ``build.web``): builds from its inputs, writes the zip output and keeps an
  unpacked copy (``<attempt>/play``) to open in a browser.
* check types ``web_zip`` (the build has index.html and JavaScript) and ``web_smoke`` (open the game in a
  headless Chromium/Edge for a few seconds: no uncaught errors, the canvas is not blank).
"""
from __future__ import annotations

import functools
import json
import glob
import http.server
import os
import re
import shutil
import subprocess
import tempfile
import threading
import zipfile
from pathlib import Path
from typing import Any, Callable

CODE = {"text/typescript": ".ts", "application/typescript": ".ts", "text/javascript": ".js",
        "application/javascript": ".js"}

INDEX_HTML = """<!doctype html>
<html lang="vi">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<link rel="icon" href="data:,">
<style>html, body, #app {{ margin: 0; width: 100%; height: 100%; overflow: hidden; background: #000; }}</style>
</head>
<body>
<div id="app"></div>
<script type="module" src="/src/main.ts"></script>
</body>
</html>
"""

MAIN_TS = """// Generated by SHAMS: opens the playable scene.
import * as scene from "{scene}";

const container = document.getElementById("app") as HTMLElement;
const mod = scene as Record<string, unknown>;
const start = (mod.start ?? mod.default ?? Object.values(mod).find((v) => typeof v === "function")) as
  ((el: HTMLElement) => unknown) | undefined;
if (typeof start === "function") {{
  Promise.resolve(start(container)).catch((e) => console.error("start() failed:", e));
}} else {{
  console.error("The scene module has no start(container) function");
}}
"""

VITE_CONFIG = """export default {
  base: "./",
  logLevel: "info",
  build: { outDir: "dist", emptyOutDir: true, target: "es2022", chunkSizeWarningLimit: 4096 },
};
"""


def _toolchain():
    from shams_packs.game import toolchain
    return toolchain


def vite_entry() -> Path | None:
    p = _toolchain().web_dir() / "node_modules" / "vite" / "bin" / "vite.js"
    return p if p.exists() else None


def _safe_rel(rel: str) -> Path:
    p = Path(rel.replace("\\", "/"))
    if p.is_absolute() or ".." in p.parts:
        p = Path(p.name)
    return p


def materialize(files: list[tuple[str, Path]], root: Path) -> list[Path]:
    out = []
    for rel, src in files:
        dest = root / _safe_rel(rel)
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, dest)
        out.append(dest)
    return out


def _scene_module(root: Path) -> Path | None:
    """The module that starts the game: one exporting start(), preferring src/scenes/."""
    cands = sorted(p for p in root.rglob("*.ts") if "node_modules" not in p.parts and not
                   re.search(r"(Tests?|\.test|\.spec)\.ts$", p.name))
    def score(p: Path) -> tuple:
        text = p.read_text(encoding="utf-8", errors="replace")
        return (bool(re.search(r"export\s+(async\s+)?function\s+start\b|export\s+(const|let)\s+start\b", text)),
                "scenes" in p.parts, "export default" in text)
    cands = [p for p in cands if p.name != "main.ts"]
    best = max(cands, key=score, default=None)
    return best


def add_entry(root: Path, title: str = "SHAMS game") -> dict:
    """index.html + src/main.ts when the project has none."""
    made = {}
    if not (root / "index.html").exists():
        (root / "index.html").write_text(INDEX_HTML.format(title=title), encoding="utf-8")
        made["index.html"] = True
    main = root / "src" / "main.ts"
    if not main.exists():
        scene = _scene_module(root)
        if scene is None:
            raise RuntimeError("no TypeScript module to start the game from")
        rel = os.path.relpath(scene, main.parent).replace("\\", "/")
        rel = rel if rel.startswith(".") else "./" + rel
        main.parent.mkdir(parents=True, exist_ok=True)
        main.write_text(MAIN_TS.format(scene=rel[:-3] if rel.endswith(".ts") else rel), encoding="utf-8")
        made["src/main.ts"] = rel
    return made


def build_web(files: list[tuple[str, Path]], *, title: str = "SHAMS game", timeout: float = 300) -> dict:
    """Returns {"ok", "dist" (Path, caller removes "work"), "work", "log", "entry"}."""
    node, vite = shutil.which("node"), vite_entry()
    if not node or vite is None:
        return {"ok": False, "unavailable": True,
                "log": "web toolchain not installed: run `shams toolchain install web`" if node
                else "Node.js not found on PATH"}
    work_root = _toolchain().web_dir() / "work"
    work_root.mkdir(parents=True, exist_ok=True)
    work = Path(tempfile.mkdtemp(prefix="build-", dir=work_root))
    try:
        materialize(files, work)
        entry = add_entry(work, title)
        (work / "vite.config.mjs").write_text(VITE_CONFIG, encoding="utf-8")
        p = subprocess.run([node, str(vite), "build", "--config", str(work / "vite.config.mjs")], cwd=work,
                           capture_output=True, text=True, timeout=timeout, encoding="utf-8", errors="replace",
                           env={**os.environ, "NO_COLOR": "1", "CI": "1"})
        log = (p.stdout + "\n" + p.stderr).strip()
        ok = p.returncode == 0 and (work / "dist" / "index.html").exists()
        return {"ok": ok, "dist": work / "dist", "work": work, "log": log[-4000:], "entry": entry}
    except (OSError, RuntimeError, subprocess.TimeoutExpired) as e:
        return {"ok": False, "work": work, "log": f"{type(e).__name__}: {e}"}


def zip_dir(src: Path, dest: Path) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(dest, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(src.rglob("*")):
            if f.is_file():
                z.write(f, f.relative_to(src).as_posix())


# --------------------------------------------------------------------------- headless browser smoke test
def find_browser() -> str | None:
    env = os.environ.get("SHAMS_BROWSER")
    if env and Path(env).exists():
        return env
    for name in ("msedge", "chrome", "google-chrome", "chromium", "chromium-browser"):
        p = shutil.which(name)
        if p:
            return p
    pats = [r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe",
            r"C:\Program Files\Microsoft\Edge\Application\msedge.exe",
            r"C:\Program Files\Google\Chrome\Application\chrome.exe",
            "/opt/pw-browsers/chromium-*/chrome-linux*/chrome", "/opt/pw-browsers/chromium*/chrome-linux*/chrome"]
    for pat in pats:
        hits = sorted(glob.glob(pat))
        if hits:
            return hits[-1]
    return None


class _Quiet(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *a):
        pass


def _serve(root: Path):
    handler = functools.partial(_Quiet, directory=str(root))
    _Quiet.extensions_map.update({".js": "text/javascript", ".mjs": "text/javascript", ".glb": "model/gltf-binary",
                                  ".wasm": "application/wasm"})
    srv = http.server.ThreadingHTTPServer(("127.0.0.1", 0), handler)
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    return srv


CDP_SCRIPT = Path(__file__).resolve().parent / "js" / "cdp_smoke.mjs"
# browser noise that is not the game's fault
_IGNORED = re.compile(r"favicon\.ico|DevTools|Autofill", re.I)


def smoke(dist: Path, *, seconds: float = 8, browser: str | None = None) -> dict:
    """Open dist/index.html over http in a headless browser. {"ok", "errors", "console", "screenshot_std"}."""
    from shams.verification import assets
    b = browser or find_browser()
    if not b:
        return {"ok": None, "why": "no Chromium/Edge/Chrome found for the headless check (set SHAMS_BROWSER)"}
    node = shutil.which("node")
    if not node:
        return {"ok": None, "why": "Node.js not found on PATH (the smoke test drives the browser with it)"}
    srv = _serve(dist)
    td = Path(tempfile.mkdtemp(prefix="smoke-"))
    try:
        shot = td / "shot.png"
        url = f"http://127.0.0.1:{srv.server_address[1]}/index.html"
        try:
            p = subprocess.run([node, str(CDP_SCRIPT), b, url, str(seconds), str(shot), str(td / "profile")],
                               capture_output=True, text=True, timeout=seconds + 120, encoding="utf-8",
                               errors="replace")
            res = json.loads(p.stdout.strip() or "{}")
        except (subprocess.TimeoutExpired, ValueError) as e:
            return {"ok": False, "errors": [f"smoke test did not finish: {type(e).__name__}"], "console": []}
        errors = [e for e in res.get("errors", []) if not _IGNORED.search(e)]
        std = None
        if shot.exists():
            try:
                std = assets.png_info(shot).get("std")
            except Exception:  # noqa: BLE001 - a bad screenshot is reported, not raised
                std = None
        blank = std is not None and std < 2.0
        ok = not errors and shot.exists() and not blank
        return {"ok": ok, "errors": errors[:10], "console": res.get("console", [])[:20], "screenshot_std": std,
                "blank": blank, "screenshot": shot.exists()}
    finally:
        srv.shutdown()
        shutil.rmtree(td, ignore_errors=True)


# --------------------------------------------------------------------------- QC check types
def _files_from_outputs(outputs: list[dict]) -> list[tuple[str, Path]]:
    files = []
    for o in sorted(outputs, key=lambda o: o.get("role", "output") == "output"):        # outputs win
        rel = o.get("path")
        if not rel or not o.get("file"):
            continue
        if o.get("media_type") in CODE or o.get("media_type", "").startswith(("model/", "image/", "audio/")):
            files.append((rel, Path(o["file"])))
    return files


def _zip_outputs(outputs: list[dict]) -> list[dict]:
    return [o for o in outputs if o.get("role", "output") == "output" and o.get("media_type") == "application/zip"]


def check_web_zip(c: dict, outputs: list[dict], settings: dict | None = None):
    zips = _zip_outputs(outputs)
    if not zips:
        return "FAIL", "missing output: no web build (zip)"
    with zipfile.ZipFile(zips[0]["file"]) as z:
        names = z.namelist()
    js = [n for n in names if n.endswith(".js")]
    if "index.html" not in names or not js:
        return "FAIL", f"build incomplete: index.html {'present' if 'index.html' in names else 'missing'}, " \
                       f"{len(js)} JavaScript file(s)"
    return "PASS", f"web build: {len(names)} files, {len(js)} JavaScript bundle(s)"


def check_web_smoke(c: dict, outputs: list[dict], settings: dict | None = None):
    """Opens the game: the zip build when there is one, else builds the task's code + inputs first."""
    zips = _zip_outputs(outputs)
    tmp = None
    work = None
    try:
        if zips:
            tmp = Path(tempfile.mkdtemp(prefix="play-"))
            with zipfile.ZipFile(zips[0]["file"]) as z:
                z.extractall(tmp)
            dist = tmp
        else:
            files = _files_from_outputs(outputs)
            if not any(Path(r).suffix in (".ts", ".js") for r, _ in files):
                return "FAIL", "missing output: no web code to run"
            r = build_web(files)
            work = r.get("work")
            if r.get("unavailable"):
                return "NOT_VERIFIED", r["log"]
            if not r["ok"]:
                return "FAIL", "build failed: " + r["log"][-1500:]
            dist = r["dist"]
        s = smoke(dist, seconds=float((c.get("check") or {}).get("seconds", 8)))
        if s["ok"] is None:
            return "NOT_VERIFIED", s["why"]
        if not s["ok"]:
            why = "; ".join(s.get("errors") or []) or ("blank screen" if s.get("blank") else "no screenshot")
            return "FAIL", "runtime errors: " + why[-1500:]
        return "PASS", f"opened in a headless browser: no uncaught errors, screen std {s.get('screenshot_std')}"
    finally:
        for d in (tmp, work):
            if d:
                shutil.rmtree(d, ignore_errors=True)


# --------------------------------------------------------------------------- worker
class WebBuildWorker:
    """build.web: Vite build of the inputs; zip output + an unpacked copy to play."""

    def __init__(self, *, entry: dict, attempts_root: Path, read_blob: Callable[[str], Path] | None = None,
                 **_: Any):
        self.attempts_root, self.read_blob = Path(attempts_root), read_blob
        self.model = "vite"

    def run(self, ctx: dict, worker_ref: dict) -> tuple[list[dict], dict]:
        from shams.workers import base_handoff, output_plan
        adir, plan = output_plan(ctx, self.attempts_root)
        zip_out = next((o for o in plan if o["media_type"] == "application/zip"), None)
        if zip_out is None:
            return [], base_handoff(ctx, worker_ref, "BLOCKED", "no zip output declared",
                                    blocked_reason="the web build writes one application/zip output")
        files = []
        for i in ctx.get("inputs", []):
            if not i.get("path"):
                continue
            src = Path(self.read_blob(i["sha256"])) if self.read_blob and i.get("sha256") else Path(i["path"])
            if i.get("media_type") in CODE or str(i.get("media_type", "")).startswith(("model/", "image/", "audio/")):
                files.append((i["path"], src))
        r = build_web(files, title=str(ctx.get("goal") or "SHAMS game")[:80])
        try:
            if r.get("unavailable"):
                return [], base_handoff(ctx, worker_ref, "BLOCKED", "web toolchain missing",
                                        blocked_reason="tool unavailable: " + r["log"])
            if not r["ok"]:
                return [], base_handoff(ctx, worker_ref, "FAILED", "vite build failed",
                                        known_issues=[{"issue": r["log"][-1500:], "severity": "high"}],
                                        blocked_reason=r["log"][-500:])
            zip_dir(r["dist"], Path(zip_out["abs"]))
            play = adir / "play"
            shutil.rmtree(play, ignore_errors=True)
            shutil.copytree(r["dist"], play)
            return [zip_out], base_handoff(
                ctx, worker_ref, "READY_FOR_QC", f"web build ready; play it from {play}",
                decisions=[{"decision": "entry files", "reason": str(r.get("entry") or "project's own")},
                           {"decision": "playable build", "reason": str(play)}])
        finally:
            if r.get("work"):
                shutil.rmtree(r["work"], ignore_errors=True)


class _WebBuildBackend:
    def bind(self, reg, role: str, cfg: dict):
        from shams.models import RoleBinding
        ok = bool(shutil.which("node")) and vite_entry() is not None
        return RoleBinding(role, "vite", "vite" if ok else None, "ok" if ok else "missing",
                           how="web toolchain" if ok else "run `shams toolchain install web` (needs Node.js)",
                           backend="web_build", config=cfg)

    def worker(self, reg, b) -> dict:
        return {"kind": "tool", "provider": "web_build", "model": "vite", "load_adapter": "none",
                "lane": "cpu", "vram_mb": 0, "config": {"impl": "web_build"}}


class WebBuildProvider:
    """Nothing stays loaded: each build is one Node process."""

    def __init__(self, **_: Any):
        pass

    def health(self) -> str:
        return "ok" if shutil.which("node") and vite_entry() is not None else "down"

    def load(self, model: str) -> None:
        return None

    def unload(self, model: str | None = None) -> None:
        return None

    def chat(self, messages, *, model: str, **opts):
        from shams.providers import ProviderError
        raise ProviderError("web_build is a build tool; use the web_build worker")
